# მომხმარებელს შეაყვანინე რიცხვი 1–5. დაბეჭდე სიტყვებით, მაგალითად: 1 → One 2 → Two გამოიყენე if / elif / else

number = int(input("Enter number between 1-5:"))

if number == 1:
     print("one")
elif number == 2:
     print("two")
elif number == 3:
     print("three")
elif number == 4:
     print("four")
else:
     print("five")